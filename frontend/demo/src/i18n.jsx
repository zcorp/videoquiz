const LanguageContext = createContext(null);

function detectInitialLanguage() {
  try {
    const savedLanguage = window.localStorage.getItem(LANGUAGE_KEY);
    if (savedLanguage === 'fr' || savedLanguage === 'en') return savedLanguage;
  } catch (error) {
    console.warn('La préférence de langue n’a pas pu être lue dans ce navigateur.', error);
  }

  const browserLanguages = window.navigator.languages?.length
    ? window.navigator.languages
    : [window.navigator.language];
  return browserLanguages.some(language => language?.toLowerCase().startsWith('fr')) ? 'fr' : 'en';
}

export function LanguageProvider({ children }) {
  const [language, setLanguage] = useState(detectInitialLanguage);
  const value = useMemo(() => ({
    language,
    setLanguage(nextLanguage) {
      setLanguage(nextLanguage);
      try {
        window.localStorage.setItem(LANGUAGE_KEY, nextLanguage);
      } catch (error) {
        console.warn('La préférence de langue n’a pas pu être enregistrée dans ce navigateur.', error);
      }
    },
    t(text) {
      return language === 'en' ? englishTranslations[text] ?? text : text;
    },
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  const context = useContext(LanguageContext);
  if (!context) throw new Error('useLanguage must be used within LanguageProvider');
  return context;
}

export function translateTopic(topic, language) {
  if (language !== 'en') return topic;
  const topics = {
    'code de la route': 'Road rules',
    'culture générale': 'General knowledge',
    géographie: 'Geography',
    histoire: 'History',
    mathématiques: 'Mathematics',
    programmation: 'Programming',
    sciences: 'Science',
    cinéma: 'Cinema',
    sport: 'Sports',
    mythologie: 'Mythology',
    animaux: 'Animals',
    football: 'Football',
    nature: 'Nature',
    animation: 'Animation',
    'développement web': 'Web development',
    fondamentaux: 'Fundamentals',
    'à classer': 'Unsorted',
    'créé ici': 'CREATED HERE',
  };
  return topics[topic.toLocaleLowerCase('fr-FR')] ?? topic;
}

export function localizeQuiz(quiz, t, language) {
  if (quiz.local || language === 'fr') return quiz;
  return {
    ...quiz,
    title: t(quiz.title),
    description: t(quiz.description),
    topic: translateTopic(quiz.topic, language),
    questions: quiz.questions.map(question => ({
      ...question,
      prompt: t(question.prompt),
      options: question.options?.map(option => t(option)),
      explanation: t(question.explanation),
    })),
  };
}
